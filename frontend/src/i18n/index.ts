export type Locale = 'zh' | 'en'

const STORAGE_KEY = 'autoflow_lang'

function getInitialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'zh') {
      return saved
    }
  } catch {
    // ignore storage errors
  }
  return 'zh'
}

